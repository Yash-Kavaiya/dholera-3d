/* ---------- Map ---------- */

const poly = (pts) => pts.map((p) => `${p.x.toFixed(0)},${p.z.toFixed(0)}`).join(" ");

/**
 * Plan of the region drawn from the same layout the 3D model uses. Units are metres; north is up.
 * `mode`: "region" (bands, roads, landmarks) or "villages" (pins and names).
 */
export function regionMap({ mode = "region", id = "map" } = {}) {
  const xs = layout.sir.map((p) => p.x);
  const zs = layout.sir.map((p) => p.z);
  const pad = 2600;
  const minX = Math.min(...xs, layout.solar.x) - pad;
  const maxX = layout.shoreX + 9000;
  const minZ = Math.min(...zs, layout.airport.z) - pad;
  const maxZ = Math.max(...zs) + pad;
  const w = maxX - minX;
  const h = maxZ - minZ;
  const label = (x, z, text, cls = "") =>
    `<text x="${x.toFixed(0)}" y="${z.toFixed(0)}" class="${cls}">${esc(text)}</text>`;
  const line = (pts, cls) => `<polyline points="${poly(pts)}" class="${cls}" />`;

  const bands = layout.bands
    .map((b, i) => `<polygon points="${poly(b.poly)}" class="band ${i < 2 ? "band-p1" : "band-later"}"><title>${b.id.toUpperCase()}</title></polygon>`)
    .join("");
  const aa = `<polygon points="${poly(layout.activation.corners)}" class="aa"><title>Activation Area, 22.54 km²</title></polygon>`;
  const sea = `<rect x="${layout.shoreX.toFixed(0)}" y="${minZ.toFixed(0)}" width="${(maxX - layout.shoreX + 4000).toFixed(0)}" height="${h.toFixed(0)}" class="sea" />`;
  const r = w / 150;

  let overlay = "";
  if (mode === "region") {
    const aaC = { x: layout.activation.cx, z: layout.activation.cz };
    overlay = `
      ${line(layout.rail, "rail")}
      ${line(layout.nh751, "nh")}
      ${line(layout.expressway, "expressway")}
      ${line(layout.airportLink, "expressway link")}
      <rect x="${(layout.solar.x - 1200).toFixed(0)}" y="${(layout.solar.z - 1000).toFixed(0)}" width="2400" height="2000" class="solar"><title>Solar park</title></rect>
      <circle cx="${layout.airport.x.toFixed(0)}" cy="${layout.airport.z.toFixed(0)}" r="${(r * 1.4).toFixed(0)}" class="poi" />
      ${label(layout.airport.x + r * 2.2, layout.airport.z + r * 0.6, "Airport", "lbl")}
      ${label(layout.solar.x + 1500, layout.solar.z + r * 0.6, "Solar park", "lbl")}
      ${label(aaC.x + 2600, aaC.z + r * 0.6, "Activation Area", "lbl lbl-strong")}
      ${label(layout.expressway[1].x + 900, layout.expressway[1].z - 900, "Expressway", "lbl lbl-road")}
      ${label(layout.shoreX + 1600, (minZ + maxZ) / 2, "Gulf of Khambhat", "lbl lbl-sea")}`;
  } else {
    overlay = layout.pinned
      .map(
        (v) => `<a href="#v-${v.id}"><circle cx="${v.x.toFixed(0)}" cy="${v.z.toFixed(0)}" r="${r.toFixed(0)}" class="pin" /><title>${esc(v.name)}</title></a>
        ${label(v.x + r * 1.6, v.z + r * 0.5, v.name, "lbl lbl-sm")}`,
      )
      .join("");
  }

  const legend =
    mode === "region"
      ? `<ul class="legend" aria-hidden="true">
          <li><span class="sw sw-plinth"></span>SIR, 920 km²</li>
          <li><span class="sw sw-p1"></span>Phase I, TP1–TP2, 153 km²</li>
          <li><span class="sw sw-later"></span>TP3–TP6</li>
          <li><span class="sw sw-aa"></span>Activation Area, 22.54 km²</li>
          <li><span class="sw sw-exp"></span>Expressway</li>
        </ul>`
      : "";

  return `<figure class="map-figure" id="${id}">
      <svg viewBox="${minX.toFixed(0)} ${minZ.toFixed(0)} ${w.toFixed(0)} ${h.toFixed(0)}" role="img" aria-labelledby="${id}-cap" style="--u:${(w / 800).toFixed(2)}">
        ${sea}
        <polygon points="${poly(layout.sir)}" class="plinth" />
        ${bands}
        ${aa}
        ${overlay}
        <g class="north" transform="translate(${(minX + w * 0.05).toFixed(0)} ${(minZ + h * 0.08).toFixed(0)})"><path d="M0 ${(-r * 3).toFixed(0)} L${(r * 1.2).toFixed(0)} ${r.toFixed(0)} L0 0 L${(-r * 1.2).toFixed(0)} ${r.toFixed(0)} Z" /><text y="${(r * 3.6).toFixed(0)}" text-anchor="middle">N</text></g>
      </svg>
      ${legend}
      <figcaption id="${id}-cap">Schematic plan. Areas match the published figures; boundaries are not the notified lines. Village pins are OpenStreetMap place nodes.</figcaption>
    </figure>`;
}

