function figureStrip() {
  return `<dl class="figures">${keyFigures
    .map(([n, u, l]) => `<div class="fig"><dt>${esc(l)}</dt><dd><span class="fig-n">${esc(n)}</span>${u ? `<span class="fig-u">${u}</span>` : ""}</dd></div>`)
    .join("")}</dl>`;
}

function projectCard(p, { compact = false } = {}) {
  const cat = categoryOf(p.category);
  const s = statusOf(p.status);
  const figs = p.figures?.length
    ? `<dl class="kv">${p.figures.map(([k, v]) => `<div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join("")}</dl>`
    : "";
  const ms = p.milestones?.length
    ? `<ol class="milestones">${p.milestones
        .map((m) => `<li><time datetime="${m.date}">${fmtDate(m.date)}</time> <span>${esc(m.text)}</span> ${cite(m.sourceIds)}</li>`)
        .join("")}</ol>`
    : "";
  return `<article class="card project" id="${p.id}" data-status="${s.id}" data-tone="${s.tone}" data-category="${p.category}">
      <header class="card-head">
        ${badge(p.status)}<span class="cat">${esc(cat.label)}</span>
      </header>
      <h3>${esc(p.title)}</h3>
      <p>${esc(p.headline)}</p>
      ${compact ? "" : figs + ms + (p.note ? `<p class="note">${esc(p.note)}</p>` : "")}
      <footer class="card-foot">
        ${compact ? `<a href="/projects/#${p.id}">Details</a>` : cite(p.sourceIds)}
        ${p.explore ? `<a class="to3d" href="/explore/#${p.explore}">View in 3D →</a>` : ""}
      </footer>
      ${compact ? "" : `<p class="asof">As of <time datetime="${p.asOf}">${fmtDate(p.asOf)}</time></p>`}
    </article>`;
}

