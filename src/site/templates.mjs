const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function esc(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** "2026-03-31" → "31 Mar 2026", "2026-08" → "Aug 2026", "2016" → "2016". */
export function fmtDate(date) {
  const m = /^(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?$/.exec(date || "");
  if (!m) return esc(date);
  const [, y, mo, d] = m;
  if (d) return `${Number(d)} ${MONTHS[Number(mo) - 1]} ${y}`;
  if (mo) return `${MONTHS[Number(mo) - 1]} ${y}`;
  return y;
}

const statusOf = (id) => statuses.find((s) => s.id === id);
const categoryOf = (id) => categories.find((c) => c.id === id);
const abs = (path) => meta.siteUrl + path;

export function badge(statusId) {
  const s = statusOf(statusId);
  return `<span class="badge tone-${s.tone}">${esc(s.label)}</span>`;
}

export function cite(ids = []) {
  if (!ids.length) return "";
  const links = ids
    .map((id) => {
      const s = sourceById(id);
      if (!s) throw new Error(`Unknown source id: ${id}`);
      return `<a class="cite cite-${s.tier}" href="/sources/#${s.id}" title="${esc(s.title)}">${esc(s.short || s.publisher)}</a>`;
    })
    .join("");
  return `<span class="cites" aria-label="Sources">${links}</span>`;
}

